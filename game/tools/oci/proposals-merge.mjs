// publish it. So it got merged to the main, or at least PR if the merge is a security issue.").
//
// A proposal = a player branch players/<who>/<slug> of chaosD6-Effects / -Skills / -Classes / -GameModels (editor-publish.mjs
// publishDefinition / publishGameModels). PUBLISHABLE = proposal-votes.mjs publishableFlag (n ≥ 10, > 60 % positive, not
// "needs rework"). A version that NEEDS REWORK is never merged (not even with --force).
//
// Two ways to main, chosen by mergeRights():
//   merge  this node's Radicle NID is a delegate of the repo (its identity document, read offline from the local Radicle
//          storage refs/rad/id) and the threshold is 1 → the proposal tip is merged (--no-ff) into main of the repo
//          checkout (/home/galt/chaosd6-<kind>s-repo) and handed to the repo-side pipeline: tools/oci/defs-publish.sh
//          <kind>s / gamemodels-publish.sh (build → checks → commit = the merge commit → git push rad main → announce to
//          the OCI seed only). Before that: votes gate, the tip carries exactly the voted version (sha256), the checkout
//          is clean, on main and not behind the published main, the def validates (effects / skills / classes: the
//          editor's validateDefinition incl. the rebalancing verdict; GameModels: checkBundle — no rebalance), the merge
//          has no conflict (index.json alone is regenerated by the repo's manifest.mjs), the repo's own check passes.
//   patch  not a delegate (or threshold > 1) → a Radicle patch for the maintainer: git push rad <tip>:refs/patches
//          -o patch.message=… from the editor's work repo, then rad sync --announce to the OCI seed only.
// DRY (DRY=1 / --dry / { dry: true }): every check runs on a throw-away clone of the checkout; nothing is pushed, the
// checkout and the game are not touched; the commands of the real run are printed.
//
// CLI (inside WSL; the wrapper proposals-merge.sh sets PATH + the ssh agent):
//   node tools/oci/proposals-merge.mjs list  [--kind effect|skill|class|gamemodels] [--all] [--json]
//   node tools/oci/proposals-merge.mjs merge --kind K --branch players/<who>/<slug> [--ns <nid>] [--commit <oid>]
//                                            [--force] [-m "message"] [--dry]
//   list: every open proposal (not yet in main) + open patches, with the vote collection (from the storage's votes/*
//   branches, else <profile dir>/proposal_votes.collected.json). --all: merged ones too.
//   merge: refuses a not-publishable version unless --force; never one that needs rework.
// Never touches the network except through the publish scripts / rad sync of a real (non-DRY) run, OCI seed only.
