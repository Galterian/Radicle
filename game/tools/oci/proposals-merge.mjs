const gitIn = (gitdir) => (args, o = {}) => execFileSync('git', ['--git-dir', gitdir, ...args], { encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'], maxBuffer: 64 << 20, ...o }).trim();
const tryGit = (g, args) => { try { return g(args); } catch { return null; } };
function runAsync(cmd, args, { cwd, env, timeout = 20 * 60e3 } = {}) {
  return new Promise((resolve) => {
    execFile(cmd, args, { cwd, env, encoding: 'utf8', timeout, maxBuffer: 64 << 20 }, (err, stdout, stderr) => resolve({ code: err ? (err.code ?? 1) : 0, out: `${stdout || ''}${stderr || ''}`, error: err ? errText({ stderr: `${stdout || ''}\n${stderr || ''}`, message: err.message }) : null }));
  });
}

// ------------------------------------------------------------------ who may merge (the repo's identity document)
/** The identity document of a Radicle repo, read offline from its storage: { delegates: [nid], threshold, name } | null.
 *  refs/rad/id is the identity COB: its tip tree holds the action blobs (0, 1 …); a "revision" action names the document
 *  blob; the first revision's document is embeds/radicle.json (older storage: radicle.json at the root). */
export function identityDoc(storageDir) {
  if (!storageDir || !fs.existsSync(storageDir)) return null;
  const g = gitIn(storageDir);
  let tip = tryGit(g, ['rev-parse', '--verify', '-q', 'refs/rad/id^{commit}']);
  if (!tip) {
    const r = (tryGit(g, ['for-each-ref', '--format=%(refname)', 'refs/namespaces/']) || '').split('\n').find(x => /\/refs\/rad\/id$/.test(x));
    tip = r ? tryGit(g, ['rev-parse', '--verify', '-q', `${r}^{commit}`]) : null;
  }
  if (!tip) return null;
  const names = (tryGit(g, ['ls-tree', '--name-only', tip]) || '').split('\n').filter(Boolean);
  const texts = [];
  for (const n of names.filter(n => /^\d+$/.test(n))) {
    try { const a = JSON.parse(g(['cat-file', '-p', `${tip}:${n}`])); if (a?.type === 'revision' && /^[0-9a-f]{40}$/.test(String(a.blob || ''))) texts.push(() => g(['cat-file', '-p', a.blob])); } catch {}
  }
  texts.push(() => g(['cat-file', '-p', `${tip}:embeds/radicle.json`]), () => g(['cat-file', '-p', `${tip}:radicle.json`]));
  for (const t of texts) {
    try {
      const d = JSON.parse(t());
      if (!Array.isArray(d?.delegates)) continue;
      return { delegates: d.delegates.map(x => String(x).replace(/^did:key:/, '')).filter(x => NID_RE.test(x)), threshold: Number(d.threshold) || 1,
        name: d.payload?.['xyz.radicle.project']?.name || null, default_branch: d.payload?.['xyz.radicle.project']?.defaultBranch || MAIN_BRANCH };
    } catch {}
  }
  return null;
}
/** May this node merge into the repo's main? → { can, why, me, delegates, threshold }. Unsure → can: false (a patch). */
export function mergeRights({ storageDir, nid }) {
  const me = NID_RE.test(String(nid || '')) ? nid : null;
  if (!me) return { can: false, why: 'no Radicle identity on this node (no ~/.radicle/keys/radicle.pub)', me: null, delegates: [], threshold: null };
  const doc = identityDoc(storageDir);
  if (!doc) return { can: false, why: `cannot read the repo's identity document (is the repo in this node's Radicle storage? ${storageDir})`, me, delegates: [], threshold: null };
  if (!doc.delegates.includes(me)) return { can: false, why: `this node (${me.slice(0, 12)}…) is not a delegate of ${doc.name || 'the repo'} — a patch goes to the maintainer`, me, ...doc };
  if (doc.threshold > 1) return { can: false, why: `${doc.name || 'the repo'} needs ${doc.threshold} delegates to move main — a patch instead`, me, ...doc };
  return { can: true, why: null, me, ...doc };
}

// ------------------------------------------------------------------ what a proposal carries
let _gm = null;
const gmMods = async () => (_gm ||= { P: await import('../../gm-proposals.mjs'), E: await import('../../editor-publish.mjs') });
/** The definition(s) a proposal tip adds / changes against main (their merge base). → [{ id, sha256, def?, bundle?, files }].
 *  effects / skills / classes: one entry per <subdir>/<id>.json changed; GameModels: one entry, the bundle (sha256 = of
 *  the signed content, the version its votes name). */
export async function proposalContent(kind, gitdir, main, tip) {
  const g = gitIn(gitdir);
  if (kind === 'gamemodels') {
    const { P, E } = await gmMods();
    const info = await P.bundleOfCommit(gitdir, main, tip, { engine: 'git' }).catch(() => null);
    if (!info) return [];
    return [{ id: info.bundle.id, sha256: E.defSha(E.gmSignedOf(info.bundle.id, info.defs)), bundle: info.bundle, defs: info.defs, files: info.files }];
  }
  const base = tryGit(g, ['merge-base', main, tip]) || main;
  const re = new RegExp(`^${SUBDIR[kind]}/(${kind}_[a-z0-9_]+)\\.json$`);
  const files = (tryGit(g, ['diff', '--name-only', base, tip]) || '').split('\n').filter(f => re.test(f));
  const out = [];
  for (const f of files) {
    let def; try { def = JSON.parse(g(['show', `${tip}:${f}`])); } catch { continue; }
    if (def?.id !== re.exec(f)[1]) continue;
    out.push({ id: def.id, sha256: defSha(def), def, files: [f] });
  }
  return out;
}

// ------------------------------------------------------------------ the vote collection of a proposal version
/** The keys a vote on this version may carry (repo = the RID with / without rad:, or the repo name; version = sha256 or commit). */
export function voteKeysOf(kind, { branch, id, sha256, commit }) {
  const repos = [...new Set([ridOf(kind), ridBare(ridOf(kind)), REPO_NAMES[kind]])];
  return [...new Set(repos.flatMap(r => [sha256, commit].filter(Boolean).map(v => `${r}|${branch}|${id}|${v}`)))];
}
/** votes[] (collectVotesFromGit / loadVotes shape) → the collection of the version (every candidate key folded, one vote per voter). */
export function collectionFromVotes(votes, kind, ref) {
  const keys = new Set(voteKeysOf(kind, ref));
  const canon = REPO_NAMES[kind] === 'chaosD6-GameModels' ? REPO_NAMES[kind] : ridOf(kind);
  const mine = (votes || []).filter(v => keys.has(v.key)).map(v => { const x = { ...v, repo: canon, sha256: ref.sha256 }; delete x.key; delete x.commit; return x; });
  return aggregate(mine);
}
/** The cached collections (<profile dir>/proposal_votes.collected.json): the largest one among the candidate keys. */
export function collectionFromCache(kind, ref, profileFile = '') {
  const c = loadCollections(collectedFile(profileFile)).collections || {};
  let best = null;
  for (const k of voteKeysOf(kind, ref)) if (c[k] && (!best || (c[k].n | 0) > (best.n | 0))) best = c[k];
  return best ? { ...best, review: reviewFlag(best), publishable: publishableFlag(best) } : aggregate([]);
}
const _stVotes = new Map();   // storageDir → { at, votes }
/** Every signed vote in a repo's storage (votes/<voter> branches; author votes dropped), cached 30 s. */
export function storageVotes(storageDir, { fresh = false } = {}) {
  if (!storageDir || !fs.existsSync(storageDir)) return null;
  const c = _stVotes.get(storageDir);
  if (c && !fresh && Date.now() - c.at < 30e3) return c.votes;
  let votes = null;
  try { votes = collectVotesFromGit({ gitdir: storageDir }).votes; } catch { votes = null; }
  _stVotes.set(storageDir, { at: Date.now(), votes });
  return votes;
}
/** The best collection we can see: the storage's votes (fresh), else / and the cache — the one with more votes. */
export function collectionOfVersion(kind, ref, { storageDir = null, profileFile = '', fresh = false } = {}) {
  const sv = storageVotes(storageDir, { fresh });
  const a = sv ? collectionFromVotes(sv, kind, ref) : aggregate([]);
  const b = collectionFromCache(kind, ref, profileFile);
  const best = (b.n | 0) > (a.n | 0) ? b : a;
  return { ...best, review: reviewFlag(best), publishable: publishableFlag(best), source: best === a && sv ? 'storage' : 'cache' };
}
/** UI summary of a collection: { n, mean, positive, share, review, needs_rework, publishable, top_tags: [{ id, label, n }] }. */
export function voteSummary(agg) {
  const n = agg?.n | 0, positive = agg?.positive | 0;
  const tags = Object.entries(agg?.tags || {}).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, 3).map(([id, k]) => ({ id, label: TAG_LABELS[id] || id, n: k }));
  return { n, mean: agg?.mean ?? null, positive, share: n ? Math.round((positive / n) * 100) : null, review: reviewFlag(agg), needs_rework: reviewFlag(agg),
    publishable: publishableFlag(agg), top_tags: tags, need: { votes: PUBLISH_MIN_VOTES, positive_share: PUBLISH_POSITIVE_SHARE } };
}
/** Why this collection may not go to main (null = it may). needs rework → always refused; not publishable → refused unless force. */
export function gateOf(agg, { force = false } = {}) {
  if (reviewFlag(agg)) return `this version NEEDS REWORK (${agg.n} votes, mean ${agg.mean} ≤ −3) — push a new version; it starts again at 0 votes`;
  if (publishableFlag(agg) || force) return null;
  const n = agg?.n | 0, p = agg?.positive | 0;
  return `not publishable yet: ${n} vote(s), ${n ? Math.round((p / n) * 100) : 0} % positive — needs ≥ ${PUBLISH_MIN_VOTES} votes and more than ${Math.round(PUBLISH_POSITIVE_SHARE * 100)} % positive`;
}

// ------------------------------------------------------------------ list (the maintainer's view)
function storageMain(g, refs) {
  if (refs.includes(`refs/heads/${MAIN_BRANCH}`)) return tryGit(g, ['rev-parse', `refs/heads/${MAIN_BRANCH}`]);
  const r = refs.find(x => new RegExp(`^refs/namespaces/[^/]+/refs/heads/${MAIN_BRANCH}$`).test(x));
  return r ? tryGit(g, ['rev-parse', r]) : null;
}
/** Every proposal of `kind` in the storage. → { available, why?, rid, main, proposals: [{ kind, rid, branch, ns, ref, commit, id,
 *  sha256, name, version, author, at, subject, merged, patches[], votes (summary), collection }] } */
export async function listProposals(kind, { storageDir = storageDirOf(kind), profileFile = '', all = false } = {}) {
  if (!fs.existsSync(storageDir)) return { available: false, why: `${REPO_NAMES[kind]} is not in this node's Radicle storage (${storageDir})`, proposals: [] };
  const g = gitIn(storageDir);
  const refs = (tryGit(g, ['for-each-ref', '--format=%(refname)', 'refs/namespaces/', 'refs/heads/']) || '').split('\n').filter(Boolean);
  const main = storageMain(g, refs);
  if (!main) return { available: false, why: 'no main in the storage', proposals: [] };
  const votes = storageVotes(storageDir, { fresh: true });
  const out = [], patches = [];
  for (const r of refs) {
    const m = /^(?:refs\/namespaces\/([^/]+)\/)?refs\/heads\/((players\/[^/]+\/[^/]+)|patches\/([0-9a-f]{40}))$/.exec(r);
    if (!m) continue;
    const [, ns, , branch, patchId] = m;
    const tip = tryGit(g, ['rev-parse', r]);
    if (!tip) continue;
    if (patchId) { patches.push({ id: patchId, ns: ns || null, tip }); continue; }
    const merged = tryGit(g, ['merge-base', '--is-ancestor', tip, main]) !== null;
    if (merged && !all) continue;
    for (const c of await proposalContent(kind, storageDir, main, tip)) {
      const ref = { branch, id: c.id, sha256: c.sha256, commit: tip };
      const agg = votes ? collectionFromVotes(votes, kind, ref) : collectionFromCache(kind, ref, profileFile);
      const msg = tryGit(g, ['log', '-1', '--format=%B', tip]) || '';
      const author = (/^Chaosd6-Author: (\S+)$/m.exec(msg) || [])[1] || null;
      const def = c.def || c.bundle || {};
      out.push({ kind, rid: ridOf(kind), branch, ns: ns || null, ref: r, commit: tip, id: c.id, sha256: c.sha256, name: def.name || c.id, version: def.version || null,
        gm_kind: c.bundle?.kind || null, files: c.files, author, at: tryGit(g, ['log', '-1', '--format=%cI', tip]), subject: msg.split('\n')[0].slice(0, 200), merged, patches: [],
        votes: voteSummary(agg), collection: agg });
    }
  }
  for (const p of patches) {
    const hit = out.filter(x => x.commit === p.tip);
    if (hit.length) { for (const x of hit) x.patches.push(p.id); continue; }
    const merged = tryGit(g, ['merge-base', '--is-ancestor', p.tip, main]) !== null;
    if (merged && !all) continue;
    for (const c of await proposalContent(kind, storageDir, main, p.tip)) {
      // a patch whose tip is no player branch: the votes of the same version (id + sha256) on any player branch
      const same = (votes || []).filter(v => v.id === c.id && v.sha256 === c.sha256);
      const agg = collectionFromVotes(same.map(v => ({ ...v })), kind, { branch: same[0]?.branch || `patches/${p.id}`, id: c.id, sha256: c.sha256 });
      const def = c.def || c.bundle || {};
      out.push({ kind, rid: ridOf(kind), branch: same[0]?.branch || null, ns: p.ns, ref: `refs/namespaces/${p.ns}/refs/heads/patches/${p.id}`, commit: p.tip, id: c.id, sha256: c.sha256,
        name: def.name || c.id, version: def.version || null, gm_kind: c.bundle?.kind || null, files: c.files, author: null, at: tryGit(g, ['log', '-1', '--format=%cI', p.tip]),
        subject: (tryGit(g, ['log', '-1', '--format=%s', p.tip]) || '').slice(0, 200), merged, patches: [p.id], votes: voteSummary(agg), collection: agg });
    }
  }
  out.sort((a, b) => String(b.at).localeCompare(String(a.at)));
  return { available: true, rid: ridOf(kind), main, proposals: out };
}

// ------------------------------------------------------------------ content checks (before the merge)
async function contentProblems(kind, c) {
  if (kind === 'gamemodels') {
    const { checkBundle } = await import('../../gm-gen.mjs');
    const r = checkBundle(c.bundle);   // the GameModels check — GameModels have no rebalance
    return r.ok ? [] : r.problems.map(p => `GameModels check: ${p}`);
  }
  const { validateDefinition } = await import('../../editor-api.mjs');
  const v = await validateDefinition(kind, c.def, { gameDir: GAME });
  return v.ok ? [] : v.errors;
}

// ------------------------------------------------------------------ merge (a delegate)
/** The default real step: the repo-side publish pipeline (build → checks → commit = the merge commit → push → announce). */
export async function runPublishScript({ kind, repoDir, message, env = process.env }) {
  const args = kind === 'gamemodels' ? [publishScriptOf(kind), '-m', message] : [publishScriptOf(kind), PLURAL[kind], '-m', message];
  return runAsync('bash', args, { env: { ...env, REPO: repoDir, DRY: '0' } });
}
export const publishCommandOf = (kind, repoDir, message) => `REPO=${repoDir} bash ${publishScriptOf(kind)}${kind === 'gamemodels' ? '' : ` ${PLURAL[kind]}`} -m ${JSON.stringify(message)}`;

/** Merge one proposal version into main of the repo checkout. source = a git dir holding `srcRef` (the Radicle storage, or
 *  the editor's work repo). expect = { id?, sha256?, commit? } the voted version. agg = its vote collection.
 *  → { ok, mode: 'merge', dry, steps: [], commands: [], error?, merged?: { commit } } */
export async function mergeProposal({ kind, source, srcRef, mainSource = source, expect = {}, agg, repoDir = repoDirOf(kind), dry = false, force = false, message = '',
  runPublish = runPublishScript, env = process.env, log = () => {} }) {
  const steps = [], say = (t) => { steps.push(t); log(t); };
  const res = (o) => ({ mode: 'merge', dry, steps, commands: [], ...o });
  const gate = gateOf(agg, { force });
  if (gate) return res({ ok: false, error: gate });
  say(`votes: ${agg.n} · ${agg.n ? Math.round((agg.positive / agg.n) * 100) : 0} % positive${publishableFlag(agg) ? ' · publishable' : ' · NOT publishable (--force)'}`);
  if (!fs.existsSync(path.join(repoDir, '.git'))) return res({ ok: false, error: `${repoDir} is not a git checkout of ${REPO_NAMES[kind]}` });
  const R = (args, o = {}) => execFileSync('git', ['-C', repoDir, ...args], { encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'], maxBuffer: 64 << 20, ...o }).trim();
  try {
    if (R(['symbolic-ref', '--short', 'HEAD']) !== MAIN_BRANCH) return res({ ok: false, error: `${repoDir} is not on ${MAIN_BRANCH}` });
    if (R(['status', '--porcelain'])) return res({ ok: false, error: `${repoDir} has uncommitted changes — commit or stash them first` });
    if (fs.existsSync(path.join(repoDir, '.git', 'MERGE_HEAD'))) return res({ ok: false, error: `${repoDir} is in the middle of a merge` });
    // the proposal tip + the published main from the source
    R(['fetch', '-q', '--no-tags', source, `+${srcRef}:refs/chaosd6/proposal`]);
    const tip = R(['rev-parse', 'refs/chaosd6/proposal^{commit}']);
    if (expect.commit && tip !== expect.commit) return res({ ok: false, error: `the branch moved: its tip is ${tip.slice(0, 8)}, the voted version is ${String(expect.commit).slice(0, 8)} — its new version needs its own votes` });
    say(`proposal ${srcRef.replace(/^refs\/namespaces\/[^/]+\//, '')} @${tip.slice(0, 8)}`);
    const head = R(['rev-parse', 'HEAD']);
    let pubMain = null;
    if (mainSource && fs.existsSync(mainSource)) {
      try { R(['fetch', '-q', '--no-tags', mainSource, `+refs/heads/${MAIN_BRANCH}:refs/chaosd6/published-main`]); pubMain = R(['rev-parse', 'refs/chaosd6/published-main']); } catch { pubMain = null; }
    }
    if (pubMain && tryGit(gitIn(path.join(repoDir, '.git')), ['merge-base', '--is-ancestor', pubMain, head]) === null) return res({ ok: false, error: `${repoDir} main is behind the published main (${pubMain.slice(0, 8)}) — pull it first (git pull rad ${MAIN_BRANCH})` });
    if (tryGit(gitIn(path.join(repoDir, '.git')), ['merge-base', '--is-ancestor', tip, head]) !== null) return res({ ok: false, error: 'already in main (nothing to merge)' });
    const content = await proposalContent(kind, path.join(repoDir, '.git'), head, tip);
    const c = expect.id ? content.find(x => x.id === expect.id) : content[0];
    if (!c) return res({ ok: false, error: `the proposal carries no ${expect.id || kind} definition` });
    if (expect.sha256 && c.sha256 !== expect.sha256) return res({ ok: false, error: `${c.id} at the tip is not the voted version (sha256 ${c.sha256.slice(0, 12)} ≠ ${String(expect.sha256).slice(0, 12)})` });
    say(`version ${c.id} sha256 ${c.sha256.slice(0, 12)} = the voted one`);
    const probs = await contentProblems(kind, c);
    if (probs.length) return res({ ok: false, error: `the definition does not pass: ${probs.slice(0, 4).join('; ')}` });
    say(kind === 'gamemodels' ? 'GameModels check: ok (no rebalance for GameModels)' : 'validates (schema, engine, rebalancing verdict)');
    const msg = message || `Merge ${c.id} ${c.def?.version || c.bundle?.version || ''} from ${srcRef.replace(/^refs\/namespaces\/[^/]+\/refs\/heads\//, '').replace(/^refs\/heads\//, '')} (votes ${agg.n}, ${agg.n ? Math.round((agg.positive / agg.n) * 100) : 0} % positive)`.replace(/\s+/g, ' ');
    // the work tree: a throw-away clone for DRY, the checkout itself for real
    let W = repoDir, tmp = null;
    if (dry) {
      tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'proposals-merge-'));
      W = path.join(tmp, 'repo');
      execFileSync('git', ['clone', '-q', '--shared', '--no-checkout', repoDir, W], { stdio: 'pipe' });
      execFileSync('git', ['-C', W, 'checkout', '-q', '-B', MAIN_BRANCH, head], { stdio: 'pipe' });
      execFileSync('git', ['-C', W, 'fetch', '-q', '--no-tags', repoDir, '+refs/chaosd6/proposal:refs/chaosd6/proposal'], { stdio: 'pipe' });
      if (fs.existsSync(path.join(repoDir, 'node_modules')) && !fs.existsSync(path.join(W, 'node_modules'))) fs.symlinkSync(path.join(repoDir, 'node_modules'), path.join(W, 'node_modules'), 'dir');
    }
    const Wg = (args) => execFileSync('git', ['-C', W, '-c', 'user.name=chaosd6-merge', '-c', 'user.email=merge@chaosd6', ...args], { encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] }).trim();
    const abort = () => { try { Wg(['merge', '--abort']); } catch {} };
    const cleanup = () => { if (tmp) try { fs.rmSync(tmp, { recursive: true, force: true }); } catch {} };
    try {
      try { Wg(['merge', '--no-ff', '--no-commit', 'refs/chaosd6/proposal']); }
      catch {
        const conflicts = (tryGit((a) => Wg(a), ['diff', '--name-only', '--diff-filter=U']) || '').split('\n').filter(Boolean);
        if (!conflicts.length || conflicts.some(f => f !== 'index.json') || !fs.existsSync(path.join(W, 'tools', 'manifest.mjs'))) { abort(); return res({ ok: false, error: `the merge conflicts in ${conflicts.join(', ') || '?'} — the author must rebase the proposal on main` }); }
        execFileSync(process.execPath, ['tools/manifest.mjs'], { cwd: W, stdio: 'pipe' });   // index.json alone: regenerate it from the merged tree
        Wg(['add', 'index.json']);
        say('index.json conflicted — regenerated by tools/manifest.mjs');
      }
      say(`merged into ${MAIN_BRANCH} (not committed yet): ${Wg(['diff', '--cached', '--name-only']).split('\n').filter(Boolean).join(', ')}`);
      // the repo's own check on the merged tree
      const node = process.execPath;
      const checks = [];
      if (fs.existsSync(path.join(W, 'tools', 'check.mjs'))) checks.push(kind === 'gamemodels' ? ['tools/check.mjs'] : ['tools/check.mjs', '--all']);
      if (fs.existsSync(path.join(W, 'tools', 'manifest.mjs'))) checks.push(['tools/manifest.mjs', '--check']);
      for (const a of checks) {
        const r = await runAsync(node, a, { cwd: W, env });
        if (r.code !== 0) { abort(); return res({ ok: false, error: `repo check ${a.join(' ')} failed: ${r.error || clipErr(r.out)}` }); }
        say(`repo check ${a.join(' ')}: ${clipErr(r.out).split(' | ').pop() || 'ok'}`);
      }
      const cmd = publishCommandOf(kind, repoDir, msg);
      if (dry) {
        abort();
        return res({ ok: true, commands: [`git -C ${repoDir} merge --no-ff --no-commit <${tip.slice(0, 8)}>`, cmd], id: c.id, sha256: c.sha256, commit: tip, message: msg });
      }
      say(`running the repo pipeline: ${cmd}`);
      const r = await runPublish({ kind, repoDir, message: msg, env });
      const after = R(['rev-parse', 'HEAD']);
      if (r.code !== 0) {
        if (after === head) { abort(); return res({ ok: false, error: `the publish pipeline stopped before its commit — the merge is undone: ${r.error || clipErr(r.out)}`, output: clipErr(r.out) }); }
        return res({ ok: false, error: `committed ${after.slice(0, 8)} but the publish did not finish: ${r.error || clipErr(r.out)} — finish it with: git -C ${repoDir} push rad ${MAIN_BRANCH} && rad sync --announce --seed ${OCI_SEED_NID}`, merged: { commit: after }, output: clipErr(r.out) });
      }
      say(`published ${MAIN_BRANCH} @${after.slice(0, 8)}`);
      return res({ ok: true, merged: { commit: after }, id: c.id, sha256: c.sha256, commit: tip, message: msg, output: clipErr(r.out) });
    } finally { cleanup(); }
  } catch (e) { return res({ ok: false, error: errText(e) }); }
  finally { for (const r of ['refs/chaosd6/proposal', 'refs/chaosd6/published-main']) { try { R(['update-ref', '-d', r]); } catch {} } }
}

// ------------------------------------------------------------------ patch (not a delegate)
/** Open a Radicle patch of `commit` (in `gitdir`, remote `rad` = the repo) for the maintainer. DRY → the commands only. */
export async function openPatch({ kind, gitdir, commit, title, body = '', dry = false, radSync = true, env = process.env }) {
  const rid = ridOf(kind);
  const push = ['--git-dir', gitdir, 'push', '-o', `patch.message=${title}`, ...(body ? ['-o', `patch.message=${body}`] : []), 'rad', `${commit}:refs/patches`];
  const sync = ['sync', rid, '--seed', OCI_SEED_NID, '--announce', '--timeout', '30'];
  const commands = [`git ${push.map(a => (/\s/.test(a) ? JSON.stringify(a) : a)).join(' ')}`, ...(radSync ? [`rad ${sync.join(' ')}`] : [])];
  const steps = [`not a delegate: a patch of ${String(commit).slice(0, 8)} for the maintainer`];
  if (dry) return { ok: true, mode: 'patch', dry, steps, commands };
  const p = await runAsync('git', push, { env, timeout: 120e3 });
  if (p.code !== 0) return { ok: false, mode: 'patch', dry, steps, commands, error: `open patch: ${p.error}` };
  const id = (/([0-9a-f]{40})/.exec(p.out) || [])[1] || null;
  steps.push(`patch ${id ? id.slice(0, 8) : 'opened'}`);
  if (radSync) {
    const s = await runAsync('rad', sync, { env, timeout: 90e3 });
    if (s.code !== 0) return { ok: true, mode: 'patch', dry, steps: [...steps, `announce failed (the patch is on this node; rad sync later): ${s.error}`], commands, patch: id };
    steps.push('announced to the OCI seed');
  }
  return { ok: true, mode: 'patch', dry, steps, commands, patch: id };
}

// ------------------------------------------------------------------ CLI
function parseArgs(argv) {
  const o = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '-m') o.message = argv[++i];
    else if (a.startsWith('--')) { const k = a.slice(2); if (['kind', 'branch', 'ns', 'commit', 'profile-file', 'repo', 'storage', 'nid'].includes(k)) o[k] = argv[++i]; else o[k] = true; }
    else o._.push(a);
  }
  return o;
}
const pct = (v) => (v.n ? `${v.share} %+` : '—');
function lineOf(p) {
  const v = p.votes;
  const flag = v.needs_rework ? 'NEEDS REWORK' : v.publishable ? 'PUBLISHABLE' : 'open';
  return `${p.merged ? '[merged] ' : ''}${p.kind.padEnd(10)} ${String(p.branch || '?').padEnd(40)} ${p.id} @${p.commit.slice(0, 8)}  votes ${String(v.n).padStart(2)} ${pct(v).padStart(6)}  ${flag}`
    + `${v.top_tags.length ? `  tags ${v.top_tags.map(t => `${t.id}×${t.n}`).join(' ')}` : ''}${p.patches.length ? `  patch ${p.patches.map(x => x.slice(0, 8)).join(',')}` : ''}${p.ns ? `  ns ${p.ns.slice(0, 12)}…` : ''}`;
}
async function cli(argv) {
  const o = parseArgs(argv);
  const cmd = o._[0] || 'list';
  const kinds = o.kind ? [o.kind] : MERGE_KINDS;
  if (kinds.some(k => !MERGE_KINDS.includes(k))) { console.error(`--kind must be ${MERGE_KINDS.join('|')}`); return 2; }
  const profileFile = o['profile-file'] || '';
  if (cmd === 'list') {
    const all = [];
    for (const k of kinds) {
      const l = await listProposals(k, { storageDir: o.storage || storageDirOf(k), profileFile, all: !!o.all });
      if (!l.available) { if (!o.json) console.log(`${REPO_NAMES[k]}: ${l.why}`); continue; }
      all.push(...l.proposals);
      if (!o.json) {
        const rights = mergeRights({ storageDir: o.storage || storageDirOf(k), nid: o.nid || (await import('../../proposal-votes.mjs')).localNodeNid() });
        console.log(`\n${REPO_NAMES[k]} (${ridOf(k)}) — main ${l.main.slice(0, 8)} — ${rights.can ? 'this node may merge (delegate)' : `this node cannot merge: ${rights.why}`}`);
        if (!l.proposals.length) console.log('  no open proposals');
        for (const p of l.proposals) console.log(`  ${lineOf(p)}`);
      }
    }
    if (o.json) console.log(JSON.stringify(all.map(({ collection, ...p }) => p), null, 2));
    return 0;
  }
  if (cmd === 'merge') {
    if (!o.kind || !o.branch) { console.error('merge needs --kind and --branch players/<who>/<slug>'); return 2; }
    const dry = !!o.dry || process.env.DRY === '1';
    const storageDir = o.storage || storageDirOf(o.kind);
    const l = await listProposals(o.kind, { storageDir, profileFile, all: true });
    if (!l.available) { console.error(`STOP: ${l.why}`); return 1; }
    const hits = l.proposals.filter(p => p.branch === o.branch && (!o.ns || p.ns === o.ns) && (!o.commit || p.commit.startsWith(o.commit)) && /refs\/heads\/players\//.test(p.ref));
    if (!hits.length) { console.error(`STOP: no proposal ${o.branch}${o.ns ? ` in ${o.ns}` : ''} in the storage (rad sync --fetch first)`); return 1; }
    if (new Set(hits.map(h => h.commit)).size > 1) { console.error(`STOP: ${o.branch} has several tips (namespaces ${hits.map(h => h.ns).join(', ')}) — pick one with --ns`); return 1; }
    const p = hits[0];
    if (p.merged) { console.error('STOP: already in main'); return 1; }
    const { localNodeNid } = await import('../../proposal-votes.mjs');
    const rights = mergeRights({ storageDir, nid: o.nid || localNodeNid() });
    if (!rights.can) { console.error(`STOP: ${rights.why}. The author's editor opens a patch instead ("Publish to main").`); return 1; }
    console.log(`${dry ? 'DRY: ' : ''}merging ${p.kind} ${p.id} (${p.branch} @${p.commit.slice(0, 8)}) into ${REPO_NAMES[p.kind]} main`);
    const r = await mergeProposal({ kind: p.kind, source: storageDir, srcRef: p.ref, expect: { id: p.id, sha256: p.sha256, commit: p.commit }, agg: p.collection,
      repoDir: o.repo || repoDirOf(p.kind), dry, force: !!o.force, message: o.message || '', log: (t) => console.log(`  ${t}`) });
    if (!r.ok) { console.error(`STOP: ${r.error}`); return 1; }
    if (dry) { console.log('\nDRY=1: nothing merged, nothing pushed. The real run does:'); for (const c of r.commands) console.log(`  ${c}`); }
    else console.log(`\ndone: ${r.merged?.commit?.slice(0, 8)} on main. Commit the game copy (defs-pins.json / catalog) with the game.`);
    return 0;
  }
  console.error('usage: proposals-merge.mjs list [--kind K] [--all] [--json] | merge --kind K --branch players/<who>/<slug> [--ns NID] [--commit C] [--force] [-m msg] [--dry]');
  return 2;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) cli(process.argv.slice(2)).then((c) => process.exit(c), (e) => { console.error(e.stack || e.message); process.exit(1); });
